"""
Phase 4B — Decision & Recommendation Engine

Responsibilities:
- Convert deterministic data-quality evidence into recommendations.
- Assign severity and priority using deterministic rules.
- Never modify the dataset.
- Never apply a remediation.
- Never use an LLM for decision-making.
- Preserve evidence for auditability.
- Support Human-in-the-Loop (HITL) approval.

Architecture:

    Phase 4A Evidence
            |
            v
    Decision Engine
            |
            v
    Recommendations
            |
            v
      Human Approval
            |
            v
    Phase 5 Remediation
"""

from __future__ import annotations

from typing import Any, Dict, List


class DecisionEngine:
    """
    Deterministic decision engine for data-quality remediation.

    The engine recommends what should happen.
    It does NOT execute any fix.

    Decision levels:
        - REVIEW_REQUIRED
        - RECOMMENDED
        - NO_ACTION
    """

    def __init__(self) -> None:
        """Initialize the deterministic decision engine."""

    def evaluate(self, evidence: Dict[str, Any]) -> Dict[str, Any]:
        """
        Convert Phase 4A evidence into structured recommendations.

        Parameters
        ----------
        evidence:
            Deterministic data-quality evidence generated by Phase 4A.

        Returns
        -------
        Dict[str, Any]
            Structured decision and recommendation contract.
        """

        if "critical_system_failure" in evidence:
            raise ValueError(
                "Critical system failure: "
                "decision-making cannot continue without valid quality evidence."
            )

        recommendations: List[Dict[str, Any]] = []

        summary = evidence.get("summary", {})
        missing_dirty = evidence.get("missing_dirty_matrix", {})
        duplicates = int(summary.get("duplicate_records", 0))
        logic_breaches = evidence.get("logic_breaches", {})
        outliers = evidence.get("numerical_outliers", {})

        # ---------------------------------------------------------
        # 1. Missing / dirty values
        # ---------------------------------------------------------

        total_missing_dirty = int(
            summary.get("total_missing_dirty_values", 0)
        )

        if total_missing_dirty > 0:
            recommendations.append(
                self._recommendation(
                    issue_type="MISSING_DIRTY_VALUES",
                    severity="HIGH",
                    priority=1,
                    evidence={
                        "total_count": total_missing_dirty,
                        "by_column": missing_dirty,
                    },
                    recommendation=(
                        "Review missing or dirty values before applying "
                        "any imputation or replacement strategy."
                    ),
                    action="REVIEW_REQUIRED",
                )
            )

        # ---------------------------------------------------------
        # 2. Duplicate records
        # ---------------------------------------------------------

        if duplicates > 0:
            recommendations.append(
                self._recommendation(
                    issue_type="DUPLICATE_RECORDS",
                    severity="MEDIUM",
                    priority=2,
                    evidence={
                        "duplicate_records": duplicates,
                    },
                    recommendation=(
                        "Review duplicate records and confirm whether they "
                        "represent genuine duplicates before removal."
                    ),
                    action="REVIEW_REQUIRED",
                )
            )

        # ---------------------------------------------------------
        # 3. Logic breaches
        # ---------------------------------------------------------

        if logic_breaches:
            total_logic_breaches = sum(
                int(count) for count in logic_breaches.values()
            )

            recommendations.append(
                self._recommendation(
                    issue_type="LOGIC_BREACH",
                    severity="HIGH",
                    priority=1,
                    evidence={
                        "total_breaches": total_logic_breaches,
                        "rules": logic_breaches,
                    },
                    recommendation=(
                        "Review records violating detected mathematical "
                        "relationships. Do not automatically overwrite "
                        "values without business confirmation."
                    ),
                    action="REVIEW_REQUIRED",
                )
            )

        # ---------------------------------------------------------
        # 4. Numerical outliers
        # ---------------------------------------------------------

        if outliers:
            total_outliers = sum(
                int(count) for count in outliers.values()
            )

            recommendations.append(
                self._recommendation(
                    issue_type="NUMERICAL_OUTLIERS",
                    severity="MEDIUM",
                    priority=2,
                    evidence={
                        "total_outliers": total_outliers,
                        "by_column": outliers,
                    },
                    recommendation=(
                        "Review numerical outliers and determine whether "
                        "they are genuine observations or data-entry errors."
                    ),
                    action="REVIEW_REQUIRED",
                )
            )

        # ---------------------------------------------------------
        # 5. No issues detected
        # ---------------------------------------------------------

        if not recommendations:
            recommendations.append(
                self._recommendation(
                    issue_type="NO_ACTION_REQUIRED",
                    severity="LOW",
                    priority=3,
                    evidence={},
                    recommendation=(
                        "No actionable data-quality issues were detected "
                        "by the current deterministic checks."
                    ),
                    action="NO_ACTION",
                )
            )

        return self._build_result(
            evidence=evidence,
            recommendations=recommendations,
        )

    @staticmethod
    def _recommendation(
        issue_type: str,
        severity: str,
        priority: int,
        evidence: Dict[str, Any],
        recommendation: str,
        action: str,
    ) -> Dict[str, Any]:
        """
        Build one auditable recommendation.
        """

        return {
            "recommendation_id": f"REC-{issue_type}",
            "issue_type": issue_type,
            "severity": severity,
            "priority": priority,
            "recommendation": recommendation,
            "action": action,
            "human_approval_required": action == "REVIEW_REQUIRED",
            "evidence": evidence,
        }

    @staticmethod
    def _build_result(
        evidence: Dict[str, Any],
        recommendations: List[Dict[str, Any]],
    ) -> Dict[str, Any]:
        """
        Build the final Phase 4B decision contract.
        """

        review_required = sum(
            1
            for item in recommendations
            if item["action"] == "REVIEW_REQUIRED"
        )

        return {
            "decision_engine": {
                "version": "1.0",
                "mode": "DETERMINISTIC",
                "llm_used": False,
                "dataset_modified": False,
            },
            "human_in_the_loop": {
                "enabled": True,
                "approval_required": review_required > 0,
                "approved_recommendations": [],
                "rejected_recommendations": [],
            },
            "recommendations": recommendations,
            "summary": {
                "total_recommendations": len(recommendations),
                "review_required": review_required,
            },
            "source_evidence": evidence,
        }